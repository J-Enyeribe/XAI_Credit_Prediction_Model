import React from 'react';
import { motion } from 'framer-motion';
import type { CounterfactualSuggestion } from '../api/types';
import { ArrowUpRight, ArrowDownRight, CheckCircle2, AlertCircle } from 'lucide-react';
 
interface CounterfactualPanelProps {
  suggestions: CounterfactualSuggestion[];
  originalProb: number;
  newProb: number;
}
 
const CounterfactualPanel: React.FC<CounterfactualPanelProps> = ({ suggestions, originalProb, newProb }) => {
  if (suggestions.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center p-8 text-center bg-[var(--bg-card)]/40 rounded-2xl border [border:var(--border-thin)]">
        <CheckCircle2 className="w-12 h-12 text-emerald-500 mb-4" />
        <h3 className="text-xl font-bold text-[var(--text-main)] mb-2">Optimal Profile</h3>
        <p className="text-[var(--text-muted)] text-sm max-w-xs">
          Your application is already in the optimal range. No actionable changes are suggested to improve your score.
        </p>
      </div>
    );
  }
 
  return (
    <div className="space-y-6">
      <div className="flex justify-between items-end mb-4">
        <div>
          <h3 className="text-2xl font-bold text-[var(--text-main)]">Path to Approval</h3>
          <p className="text-[var(--text-muted)] text-sm">Suggested changes to flip the decision</p>
        </div>
           <div className="text-right">
             <div className="text-[10px] text-[var(--text-muted)] uppercase font-bold">Prob. Reduction</div>
             <div className="text-xl font-mono font-bold text-rose-600">
               -{(Math.abs(originalProb - newProb) * 100).toFixed(2)}%
             </div>
           </div>
      </div>
 
      <div className="grid gap-4">
        {suggestions.map((s, i) => (
          <motion.div 
            key={i}
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: i * 0.1 }}
            className="group p-4 bg-[var(--bg-card)]/30 hover:bg-[var(--bg-card)]/60 rounded-xl border [border:var(--border-thin)] transition-all hover:border-[var(--accent)]/50"
          >
            <div className="flex justify-between items-start mb-3">
              <div className="flex items-center gap-3">
                <div className={`p-2 rounded-lg ${
                  s.impact === 'high' ? 'bg-rose-600 text-white' : 
                  s.impact === 'medium' ? 'bg-amber-500 text-white' : 
                  'bg-[var(--bg-card)] text-[var(--text-main)] border [border:var(--border-thin)]'
                }`}>
                  {s.delta > 0 ? <ArrowUpRight size={16} /> : <ArrowDownRight size={16} />}
                </div>
                <span className="font-bold text-[var(--text-main)]">{s.feature}</span>
              </div>
              <span className={`text-[10px] uppercase font-bold px-2 py-0.5 rounded-full ${
                s.impact === 'high' ? 'bg-rose-500/20 text-rose-600' : 
                s.impact === 'medium' ? 'bg-amber-500/20 text-amber-600' : 
                'bg-blue-500/20 text-blue-600'
              }`}>
                {s.impact} Impact
              </span>
            </div>
            
            <div className="flex justify-between items-center">
              <p className="text-sm text-[var(--text-muted)] italic">{s.action}</p>
              <div className="flex items-center gap-4 text-xs font-mono">
                <span className="text-carbon_black-600">{s.original_value}</span>
                <span className="text-[var(--accent)]">→</span>
                <span className="text-[var(--text-main)] font-bold">{s.suggested_value}</span>
              </div>
            </div>
          </motion.div>
        ))}
      </div>
      
      <div className="p-4 bg-blue-500/5 rounded-lg border border-blue-500/20 flex gap-3">
        <AlertCircle className="w-5 h-5 text-blue-500 shrink-0" />
        <p className="text-[11px] text-blue-600/80 leading-relaxed">
          These suggestions are generated by the XAI engine to show the minimal changes needed for approval. 
          Actual credit decisions may depend on additional regulatory factors.
        </p>
      </div>
    </div>
  );
};
 
export default CounterfactualPanel;
